"""Generates GuildTradebook/Data/RecipeItems.lua: recipe item -> recipe it teaches.

The recipe item tooltip ("Known in your guild by ...") needs that link. Names
can not provide it: item and recipe are worded differently, more so in German
("Rezept: Arkanit transmutieren" teaches "Transmutieren: Arkanit"), and some
recipes share a name.

Source: the game's own tables as published by wago.tools. Run it again when a
game patch adds recipes.

Usage:
  python tools/recipe_items.py <build>      e.g. 1.60.1.70790
"""
import csv
import io
import os
import sys
import urllib.request

# Blacksmithing, Leatherworking, Alchemy, Herbalism, Cooking, Mining, Tailoring,
# Engineering, Enchanting, Fishing, Skinning, First Aid.
SKILL_LINES = {164, 165, 171, 182, 185, 186, 197, 202, 333, 356, 393, 129}
ITEM_CLASS_RECIPE = 9
SUBCLASS_BOOK = 0        # class skill books, not profession recipes
TRIGGER_LEARN = "6"      # the item effect that teaches the spell
PER_LINE = 8
OUT = os.path.join(os.path.dirname(__file__), "..", "GuildTradebook", "Data", "RecipeItems.lua")


def table(name, build):
    url = f"https://wago.tools/db2/{name}/csv?build={build}"
    request = urllib.request.Request(url, headers={"User-Agent": "GuildTradebook-tools"})
    with urllib.request.urlopen(request, timeout=300) as response:
        text = response.read().decode("utf-8")
    return list(csv.DictReader(io.StringIO(text)))


def build_map(build):
    recipe_class = {
        int(r["ID"])
        for r in table("Item", build)
        if int(r["ClassID"]) == ITEM_CLASS_RECIPE and int(r["SubclassID"]) != SUBCLASS_BOOK
    }
    # Items without a row here do not exist in the game.
    named = {int(r["ID"]) for r in table("ItemSparse", build) if r["Display_lang"]}
    recipes = {int(r["Spell"]) for r in table("SkillLineAbility", build) if int(r["SkillLine"]) in SKILL_LINES}
    learn = {r["ID"]: int(r["SpellID"]) for r in table("ItemEffect", build) if r["TriggerType"] == TRIGGER_LEARN}

    taught = {}
    for r in table("ItemXItemEffect", build):
        item, spell = int(r["ItemID"]), learn.get(r["ItemEffectID"])
        if spell in recipes and item in recipe_class and item in named:
            taught.setdefault(item, set()).add(spell)
    return taught


def lua(build, taught):
    lines = [
        "-- Generated by tools/recipe_items.py from wago.tools, build %s. Do not edit." % build,
        "-- [recipe item] = recipe (spell) it teaches, or a list when it teaches several.",
        "local _, ns = ...",
        "",
        "ns.RecipeItems = {",
    ]
    row = []
    for item in sorted(taught):
        spells = sorted(taught[item])
        value = str(spells[0]) if len(spells) == 1 else "{" + ",".join(map(str, spells)) + "}"
        row.append(f"[{item}]={value},")
        if len(row) == PER_LINE:
            lines.append("\t" + "".join(row))
            row = []
    if row:
        lines.append("\t" + "".join(row))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    build = sys.argv[1]
    taught = build_map(build)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(lua(build, taught))
    several = sum(1 for spells in taught.values() if len(spells) > 1)
    print(f"{len(taught)} recipe items, {several} teach several recipes -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
